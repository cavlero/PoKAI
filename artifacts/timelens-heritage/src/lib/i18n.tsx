const TRANSLATIONS: Record<Lang, Dict> = { en, bg, pl, sk, uk };
const STORAGE_KEY = "pokai_lang";
const VALID: Lang[] = ["en", "bg", "pl", "sk", "uk"];

function readLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (v && VALID.includes(v)) return v;
  } catch {
    /* ignore */
  }
  return "en";
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string };

const LanguageContext = createContext<Ctx>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);

  useEffect(() => {
    try {
      document.documentElement.lang = lang;
    } catch {
      /* ignore */
    }
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback((key: string) => TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? key, [lang]);

  return <LanguageContext.Provider value={{ lang, setLang, t }}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  return useContext(LanguageContext);
}
